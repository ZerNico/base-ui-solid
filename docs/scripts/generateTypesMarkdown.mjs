import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

// Port note: upstream generates each page's `types.md` with `pnpm docs:validate`. The port renders
// its API reference from `docs/reference/*.json` (see `generateReference.mjs`), so this writes the
// same `types.md` snapshots from that JSON, keeping them in sync with what the site renders.
const docsRoot = fileURLToPath(new URL('..', import.meta.url));
const pagesRoot = resolve(docsRoot, 'src/app/(docs)/solid');

async function findTypesModules(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const results = await Promise.all(
    entries.map(async (entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        return findTypesModules(path);
      }
      return entry.name === 'types.ts' ? [path] : [];
    }),
  );
  return results.flat();
}

function cell(value) {
  return String(value ?? '-')
    .trim()
    .replaceAll('|', '\\|')
    .replaceAll('\n', '&#xA;');
}

function code(value) {
  return value === undefined || value === '' || value === '-' ? '-' : `\`${value}\``;
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => ':--').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n');
}

export function referenceToMarkdown(reference) {
  const blocks = [];
  for (const [name, entry] of Object.entries(reference)) {
    blocks.push(`### ${name}`);
    if (entry.description) {
      blocks.push(entry.description.trim());
    }
    if (entry.props?.length) {
      blocks.push(
        `**${name} Props:**`,
        table(
          ['Prop', 'Type', 'Default', 'Description'],
          entry.props.map((prop) => [prop.name, code(prop.type), prop.default, prop.description]),
        ),
      );
    }
    if (entry.dataAttributes?.length) {
      blocks.push(
        `**${name} Data Attributes:**`,
        table(
          ['Attribute', 'Type', 'Description'],
          entry.dataAttributes.map((item) => [item.name, code(item.type), item.description]),
        ),
      );
    }
    if (entry.cssVariables?.length) {
      blocks.push(
        `**${name} CSS Variables:**`,
        table(
          ['Variable', 'Type', 'Description'],
          entry.cssVariables.map((item) => [item.name, code(item.type), item.description]),
        ),
      );
    }
    for (const type of entry.additionalTypes ?? []) {
      blocks.push(`### ${type.name}`, `\`\`\`typescript\n${type.source.trim()}\n\`\`\``);
    }
  }
  return blocks.join('\n\n');
}

const modules = await findTypesModules(pagesRoot);
await Promise.all(
  modules.map(async (typesModule) => {
    const pageDirectory = resolve(typesModule, '..');
    const source = await readFile(typesModule, 'utf8');
    const referencePath = source.match(/import reference from '([^']+)'/)?.[1];
    if (!referencePath) {
      return;
    }
    const reference = JSON.parse(await readFile(resolve(pageDirectory, referencePath), 'utf8'));
    const page = await readFile(join(pageDirectory, 'page.mdx'), 'utf8');
    const title = page.match(/^# (.+)$/m)?.[1] ?? '';
    const markdown = [
      `# ${title}`,
      `[//]: types.ts '<-- Autogenerated By (do not edit the following markdown directly), run: pnpm --filter docs generate-types-md'`,
      '## API Reference',
      referenceToMarkdown(reference),
    ].join('\n\n');
    const output = join(pageDirectory, 'types.md');
    const options = (await prettier.resolveConfig(output)) ?? {};
    await writeFile(output, await prettier.format(markdown, { ...options, filepath: output }));
  }),
);
